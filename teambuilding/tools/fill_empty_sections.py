def next_heading(lines, i):
    """返回 i 之后第一个标题的行号（没有则返回 len）"""
    j = i + 1
    while j < len(lines):
        if re.match(r'^#{1,6}\s', lines[j].strip()):
            return j
        j += 1
    return len(lines)


def main():
    changed = 0
    problems = []

    for (rel, heading), body in FILLS.items():
        p = BASE / rel
        lines = p.read_text(encoding='utf-8').split('\n')
        hits = [k for k, l in enumerate(lines) if l.strip() == heading]
        if len(hits) != 1:
            problems.append(f'{rel} :: {heading} :: 命中 {len(hits)} 处')
            continue
        i = hits[0]
        if next_heading(lines, i) - i > 1 + len(body) + 4:
            problems.append(f'{rel} :: {heading} :: 已有内容，跳过')
            continue
        j = next_heading(lines, i)
        lines[i + 1:j] = [''] + body + ['']
        p.write_text('\n'.join(lines), encoding='utf-8')
        changed += 1

    for rel, (anchor, tail) in ADD_TAIL.items():
        p = BASE / rel
        text = p.read_text(encoding='utf-8')
        if '### Future（未来）' in text:
            problems.append(f'{rel} :: Future 已存在')
            continue
        text = text.rstrip('\n') + '\n' + tail
        p.write_text(text, encoding='utf-8')
        changed += 1

    for rel, heading in VARIANT_FIX.items():
        p = BASE / rel
        lines = p.read_text(encoding='utf-8').split('\n')
        hits = [k for k, l in enumerate(lines) if l.strip().startswith('| **时间紧')]
        if len(hits) != 1:
            problems.append(f'{rel} :: 变体表首行命中 {len(hits)} 处')
            continue
        k = hits[0]
        if any(l.strip() == heading for l in lines):
            problems.append(f'{rel} :: 变体标题已存在')
            continue
        lines[k:k] = [heading, '', '| 场景 | 调整方案 |', '|------|---------|']
        # 去掉插入点上方的多余空行
        while k - 1 >= 0 and lines[k - 1].strip() == '' and lines[k - 2].strip() == '':
            del lines[k - 1]
            k -= 1
        p.write_text('\n'.join(lines), encoding='utf-8')
        changed += 1

    print(f'已修改 {changed} 处')
    for x in problems:
        print('  ! ' + x)
    return 0 if not problems else 1


