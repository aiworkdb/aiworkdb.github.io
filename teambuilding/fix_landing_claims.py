def eol_of(t):
    return '\r\n' if '\r\n' in t else '\n'


changed = []
for (cat, gid), (params, paras) in SPECS.items():
    p = os.path.join(G, cat, gid + '.md')
    t = io.open(p, encoding='utf-8', newline='').read()
    eol = eol_of(t)
    i = t.find(HEAD)
    if i < 0:
        print('!! 未找到段落:', cat, gid)
        continue
    j = t.find(eol + '## ', i + len(HEAD))
    end = len(t) if j < 0 else j
    block = [HEAD, '',
             '> ⚠️ **还没有任何现成流程收录它** —— 它属于「挑一个环节塞进去」型：本页有完整玩法，但没有配套时间轴。按参数 %s，能落地的位置是：' % params,
             '']
    for x in paras:
        block += ['> ' + x, '>']
    block += [TAIL, '']
    new = eol.join(block)
    out = t[:i] + new + t[end:]
    io.open(p, 'w', encoding='utf-8', newline='').write(out)
    changed.append('%s/%s' % (cat, gid))

print('已重写 %d 款：' % len(changed))
